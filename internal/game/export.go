package game

import (
	"fmt"
	"strings"
	"time"

	"github.com/jsperandio/pokemon-simulator/internal/delphi"
)

// ExportPage is the page File → Export POKéMON information... writes,
// generated at now: the party and the POKéDEX as HTML, byte for byte as
// the original wrote it, unclosed POKéDEX rows included, in cp1252 with
// CRLF line endings. The date is printed as Windows' US English locale
// prints it (the original followed the system's), and the POKéDEX count is
// the Statistics window's.
func (g *Game) ExportPage(now time.Time) []byte {
	var sb strings.Builder
	line := func(s string) {
		sb.WriteString(s)
		sb.WriteString("\r\n")
	}
	player := g.Stats.Name
	line(`<html><head><meta name="generator" content="POKéMON Simulator"><style>body { background-color: white; background-image: none; font-family: Arial,sans-serif; color: black; font-size: 10pt;} table{ background-image: none; font-family: Arial,sans-serif; color: black; font-size: 10pt;}</style><meta http-equiv="content-type" content="text/html; charset=iso-8859-1"><title>POKéMON Information for ` + player + `</title></head><body>`)
	line("<h1>POKéMON Information for " + player + "</h1><p>Generated by POKéMON Simulator " + now.Format("1/2/2006 3:04:05 PM"))
	line("<p><table border><tr><td><b>Index</b></td><td><b>Number/Name</b></td><td><b>Level</b></td><td><b>Experience Points</b></td><td><b>...to next level</b></td></tr>")

	for i, m := range g.Party() {
		var toNext uint32 // (L+1)³ − XP in 32 bits, printed unsigned: a lagging level wraps

		if m.Level != 100 {
			n := uint32(m.Level) + 1
			toNext = n*n*n - m.XP
		}

		line(fmt.Sprintf("<tr bgcolor=%s><td>%d</td><td># %03d %s</td><td>%d</td><td>%d</td><td>%d</td></tr>",
			rowColor(i), i+1, m.Species, g.shinyName(m), m.Level, m.XP, toNext))
	}

	line(fmt.Sprintf("</table><p><table border><tr><td><b>In POKéDEX (%d/386)</b></td></tr>", g.PokedexCount()))

	row := 0

	for spc := 1; spc < len(g.InPokedex); spc++ {
		if g.InPokedex[spc] {
			line(fmt.Sprintf("<tr bgcolor=%s><td># %03d %s", rowColor(row), spc, g.name(spc)))

			row++
		}
	}

	line("</table></body></html>")

	return delphi.EncodeANSI(sb.String())
}

// rowColor alternates the rows' colours, grey first.
func rowColor(i int) string {
	if i%2 == 0 {
		return "#C0C0C0"
	}

	return "#FFFFFF"
}
