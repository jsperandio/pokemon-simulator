// Package export writes the page of File → Export POKéMON information...:
// the party and the POKéDEX as HTML, byte for byte as the original wrote
// it (notes/persistence.md), unclosed POKéDEX rows included.
package export

import (
	"fmt"
	"strings"
	"time"

	"github.com/jsperandio/pokemon-simulator/internal/delphi"
)

// Entry is a species on the page.
type Entry struct {
	Number int
	Name   string
}

// Member is a party member.
type Member struct {
	Entry
	Level uint8
	XP    uint32
}

// Info is what the page shows.
type Info struct {
	Player  string
	Party   []Member
	Pokedex []Entry // the registered species, by number
	// PokedexCount is the Statistics window's "In POKéDEX" figure, which
	// counts species 1–251 only; the page copies it.
	PokedexCount int
	// Date is when the page was generated, printed as Windows' US English
	// locale prints it (the original followed the system's).
	Date time.Time
}

// Page returns the page, in cp1252 with CRLF line endings.
func Page(info Info) []byte {
	var sb strings.Builder
	line := func(s string) {
		sb.WriteString(s)
		sb.WriteString("\r\n")
	}
	line(`<html><head><meta name="generator" content="POKéMON Simulator"><style>body { background-color: white; background-image: none; font-family: Arial,sans-serif; color: black; font-size: 10pt;} table{ background-image: none; font-family: Arial,sans-serif; color: black; font-size: 10pt;}</style><meta http-equiv="content-type" content="text/html; charset=iso-8859-1"><title>POKéMON Information for ` + info.Player + `</title></head><body>`)
	line("<h1>POKéMON Information for " + info.Player + "</h1><p>Generated by POKéMON Simulator " + info.Date.Format("1/2/2006 3:04:05 PM"))
	line("<p><table border><tr><td><b>Index</b></td><td><b>Number/Name</b></td><td><b>Level</b></td><td><b>Experience Points</b></td><td><b>...to next level</b></td></tr>")

	for i, m := range info.Party {
		toNext := 0

		if m.Level != 100 {
			n := int(m.Level) + 1
			toNext = n*n*n - int(m.XP)
		}

		line(fmt.Sprintf("<tr bgcolor=%s><td>%d</td><td># %03d %s</td><td>%d</td><td>%d</td><td>%d</td></tr>",
			rowColor(i), i+1, m.Number, m.Name, m.Level, m.XP, toNext))
	}

	line(fmt.Sprintf("</table><p><table border><tr><td><b>In POKéDEX (%d/386)</b></td></tr>", info.PokedexCount))

	for i, e := range info.Pokedex {
		line(fmt.Sprintf("<tr bgcolor=%s><td># %03d %s", rowColor(i), e.Number, e.Name))
	}

	line("</table></body></html>")

	return delphi.EncodeANSI(sb.String())
}

// rowColor alternates the rows' colours, grey first.
func rowColor(i int) string {
	if i%2 == 0 {
		return "#C0C0C0"
	}

	return "#FFFFFF"
}
